import assert from "node:assert/strict";
import { parseGoalRequest, goalMaxRounds, goalRoundPrompt, goalSelfVerdict, runGoalCheck } from "../../recovered/esm/000-extension.js/goal-loop.mjs";
assert.equal(parseGoalRequest(undefined, "hello"), null);
assert.equal(parseGoalRequest("compact", "/goal x"), null);
assert.deepEqual(parseGoalRequest(undefined, "/goal"), { error: "usage" });
let g = parseGoalRequest(undefined, '/goal 修好测试 --check "npm test -- --runInBand" --max 7');
assert.equal(g.goal, "修好测试"); assert.equal(g.check, "npm test -- --runInBand"); assert.equal(g.max, 7);
g = parseGoalRequest("goal", "让构建通过 --check=node -v");
assert.equal(g.goal, "让构建通过"); assert.equal(g.check, "node -v");
g = parseGoalRequest(undefined, "/goal 跑通 --check npm run build --max 3");
assert.equal(g.check, "npm run build"); assert.equal(g.max, 3);
assert.equal(goalMaxRounds({}, undefined), 5); assert.equal(goalMaxRounds({ max: 99 }, 3), 50); assert.equal(goalMaxRounds({}, 3), 3); assert.equal(goalMaxRounds({}, null), 5);
assert.match(goalRoundPrompt({ goal: "A" }, 1, 5), /第 1\/5 轮[\s\S]*GOAL_DONE/);
assert.match(goalRoundPrompt({ goal: "A", check: "x" }, 2, 5, { feedback: "退出码 1" }), /第 2\/5 轮[\s\S]*退出码 1[\s\S]*`x`/);
assert.equal(goalSelfVerdict("做完了\n\nGOAL_DONE").ok, true);
assert.equal(goalSelfVerdict("**GOAL_DONE**").ok, true);
let v = goalSelfVerdict("还差一点\nGOAL_CONTINUE: 补测试"); assert.equal(v.ok, false); assert.match(v.feedback, /补测试/);
assert.equal(goalSelfVerdict("没有标记").ok, false);
v = await runGoalCheck('node -e "process.exit(0)"', process.cwd()); assert.equal(v.ok, true);
v = await runGoalCheck('node -e "console.log(\'boom\');process.exit(3)"', process.cwd()); assert.equal(v.ok, false); assert.equal(v.code, 3); assert.match(v.feedback, /boom/);
v = await runGoalCheck('node -e "setTimeout(()=>{},60000)"', process.cwd(), { timeoutMs: 1500 }); assert.equal(v.timedOut, true);
console.log("PASS goal-loop selfcheck");
