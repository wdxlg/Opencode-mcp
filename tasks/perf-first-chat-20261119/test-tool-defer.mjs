// tool-defer-step01 test: core tools advertised, others deferred behind tool_search; search/load appends.
import { createRequire } from "node:module";
globalThis.require = createRequire(import.meta.url);
globalThis.__filename = new URL("../../opencode/resources/app/extensions/opencode/runtime/agent-host.js", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const { buildAgentToolCatalog, TOOL_SEARCH_TOOL_NAME } = await import("../../recovered/esm/002-agent-host.js/agent-tool-catalog.mjs");
const { buildChatRequestBody } = await import("../../recovered/esm/002-agent-host.js/agent-request.mjs");
const assert = (c, m) => { if (!c) { console.error("FAIL", m); process.exit(1); } };
const core = ["read_files", "find_files", "search_files", "list_directory", "apply_patch", "run_command"];
const extra = Array.from({ length: 40 }, (_, i) => `bridge_extra_${String(i).padStart(2, "0")}`);
extra.push("bridge_memory_recall");
const mk = (name) => ({ name, description: name === "bridge_memory_recall" ? "Recall archived memory notes" : `extra tool ${name}`, inputSchema: { type: "object", properties: { x: { type: "string" } } } });
const client = { listTools: async () => ({ tools: [...core, ...extra].map(mk) }) };
const input = { workspaceRoot: "E:/w", workspaceRoots: ["E:/w"] };
const c = await buildAgentToolCatalog(input, client, {});
const sent = c.tools.map((t) => t.function.name);
assert(sent.includes(TOOL_SEARCH_TOOL_NAME), "tool_search advertised");
assert(!sent.includes("bridge_extra_00"), "extra deferred");
assert(sent.includes("read_files") && sent.includes("spawn_subagent"), "core advertised");
assert(c.availableToolNames.has("bridge_extra_00") && c.availableToolNames.has(TOOL_SEARCH_TOOL_NAME), "full names callable");
assert(!c.availableTools.some((t) => t.name === TOOL_SEARCH_TOOL_NAME), "tool_search not in checkpoint tool list");
const desc = c.tools.find((t) => t.function.name === TOOL_SEARCH_TOOL_NAME).function.description;
assert(desc.includes("bridge_memory_recall"), "names listed");
const before = JSON.stringify(c.tools);
const out = c.searchDeferredTools({ query: "memory recall" });
assert(/Loaded 1 tool/.test(out) && out.includes("bridge_memory_recall") && out.includes("parameters"), "search loads " + out.slice(0, 200));
assert(JSON.stringify(c.tools).startsWith(before.slice(0, -1)), "append keeps prefix");
assert(c.tools.at(-1).function.name === "bridge_memory_recall" && c.codexTools.at(-1).name === "bridge_memory_recall" && c.anthropicTools.at(-1).name === "bridge_memory_recall", "all formats appended");
c.loadDeferredTools(["bridge_extra_05", "bridge_extra_05", "nope"]);
assert(c.tools.filter((t) => t.function.name === "bridge_extra_05").length === 1, "load once");
assert(/No matching/.test(c.searchDeferredTools({ query: "zzzz" })), "no match");
const off = await buildAgentToolCatalog({ ...input, deferTools: false }, client, {});
assert(off.tools.length === off.availableTools.length && !off.availableToolNames.has(TOOL_SEARCH_TOOL_NAME), "off sends all");
const small = await buildAgentToolCatalog(input, { listTools: async () => ({ tools: core.map(mk) }) }, {});
assert(!small.availableToolNames.has(TOOL_SEARCH_TOOL_NAME), "few tools: no defer");
const r = { input2: { model: "m" }, messages: [], tools: [], promptCacheKey: "oc-k" };
assert(buildChatRequestBody(r, true, true).prompt_cache_key === "oc-k" && !("prompt_cache_key" in buildChatRequestBody(r, true, false)), "cache key gated");
console.log(JSON.stringify({ ok: true, advertised: sent.length, total: c.availableTools.length, sentChars: before.length, fullChars: JSON.stringify(off.tools).length }));
